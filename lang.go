// t — короткая фабрика строки по ключу для текущего языка игры.
func (g *Game) t(key string) string {
	m, ok := texts[g.langID]
	if !ok {
		m = texts[LangEN]
	}
	if s, ok := m[key]; ok {
		return s
	}
	if s, ok := texts[LangEN][key]; ok {
		return s
	}
	return "?"
}
